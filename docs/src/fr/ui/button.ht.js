import { h2, p } from 'javascript-to-html'
import { code, demo, propsTable, uiLayout } from '../../lib/fr.js'
import { uiHead } from '../../lib/ui-demo.js'

export default () =>
  uiLayout({
    title: 'Bouton',
    description:
      'Les boutons permettent d’agir. Cinq variantes, cinq couleurs, trois tailles — et une ancre dès qu’il s’agit de naviguer.',
    activeHref: '/fr/ui/button',
    extraHead: uiHead(),
    children: [
      p(
        'Un bouton, c’est ce sur quoi on clique pour faire arriver quelque chose. ',
        code('button()'),
        ' rend un vrai ',
        code('<button>'),
        ' avec ',
        code('type="button"'),
        ' : en poser un dans un formulaire ne le soumet donc pas par accident.',
      ),

      h2('Bouton de base'),
      p(
        'Par défaut : solide, primary, taille moyenne. Les enfants sont le libellé ; tout le reste est une prop.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  button('Un'),
  button('Deux'),
  button('Trois'),
)`),

      h2('Variantes'),
      p(
        'Cinq niveaux d’emphase, du seul appel à l’action de la page jusqu’à ce qui se lit comme un lien.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'solid' }, 'Solid'),
  button({ variant: 'soft' }, 'Soft'),
  button({ variant: 'outline' }, 'Outline'),
  button({ variant: 'ghost' }, 'Ghost'),
  button({ variant: 'link' }, 'Link'),
)`),

      h2('Couleurs'),
      p(
        'Tous les composants thématisés puisent dans les mêmes cinq palettes : un bouton ',
        code("color: 'danger'"),
        ' et une alerte ',
        code("color: 'danger'"),
        ' s’accordent sans que l’un connaisse l’autre.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ color: 'primary' }, 'Primary'),
  button({ color: 'neutral' }, 'Neutral'),
  button({ color: 'success' }, 'Success'),
  button({ color: 'warning' }, 'Warning'),
  button({ color: 'danger' }, 'Danger'),
)`),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'soft', color: 'primary' }, 'Primary'),
  button({ variant: 'soft', color: 'neutral' }, 'Neutral'),
  button({ variant: 'soft', color: 'success' }, 'Success'),
  button({ variant: 'soft', color: 'warning' }, 'Warning'),
  button({ variant: 'soft', color: 'danger' }, 'Danger'),
)`),

      h2('Tailles'),
      demo(`stack({ direction: 'row', gap: 'md', align: 'center', wrap: true },
  button({ size: 'sm' }, 'Petit'),
  button({ size: 'md' }, 'Moyen'),
  button({ size: 'lg' }, 'Grand'),
)`),

      h2('Icônes'),
      p(
        'Passez n’importe quel balisage SVG dans ',
        code('startIcon'),
        ' ou ',
        code('endIcon'),
        '. Les icônes sont dimensionnées en ',
        code('em'),
        ' : elles suivent le bouton au lieu d’exiger une taille à elles.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({
    startIcon: icon('plus'),
  }, 'Nouvelle page'),
  button({
    variant: 'outline',
    endIcon: icon('arrow-right'),
  }, 'Continuer'),
)`),

      h2('Bouton-icône'),
      p(
        code('iconButton()'),
        ' est un bouton carré qui porte une seule icône. Son ',
        code('label'),
        ' est obligatoire — il devient le nom accessible que l’icône ne peut pas fournir, et l’infobulle au survol.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  iconButton({ label: 'Ajouter', icon: icon('plus') }),
  iconButton({ label: 'Modifier', variant: 'soft', icon: icon('edit') }),
  iconButton({ label: 'Supprimer', variant: 'ghost', color: 'danger', icon: icon('trash') }),
)`),

      h2('Chargement et désactivation'),
      p(
        code('loading'),
        ' met un spinner à la place et pose ',
        code('aria-busy'),
        ', en laissant le libellé pour que le bouton ne change pas de largeur en pleine action.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ loading: true }, 'Enregistrement'),
  button({ variant: 'outline', loading: true }, 'Vérification'),
  button({ disabled: true }, 'Désactivé'),
  button({ variant: 'soft', disabled: true }, 'Désactivé'),
)`),

      h2('Liens'),
      p(
        'Donnez un ',
        code('href'),
        ' à un bouton et il rend une ',
        code('<a>'),
        ' — le bon élément pour ce qui navigue. Les ancres n’ont pas d’état désactivé, donc ',
        code('disabled'),
        ' devient ',
        code('aria-disabled'),
        ' et la retire de l’ordre de tabulation.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ href: '/fr/docs' }, 'Lire la documentation'),
  button({ href: '/fr/docs/ui', variant: 'outline' }, 'Composants'),
  button({ href: '/fr/docs', variant: 'link' }, 'Lien simple'),
)`),

      h2('Pleine largeur'),
      demo(`button({ block: true, size: 'lg' }, 'Déployer le site')`, { align: 'stretch' }),

      h2('Props'),
      p(
        'Tout ce qui n’est pas listé ici tombe sur l’élément rendu sous forme d’attribut — ',
        code('id'),
        ', ',
        code('data-*'),
        ', ',
        code('onclick'),
        ', ',
        code('popovertarget'),
        ' et le reste.',
      ),
      propsTable([
        ['variant', "'solid' | 'soft' | 'outline' | 'ghost' | 'link'", "'solid'", 'Le poids que porte le bouton.'],
        ['color', "'primary' | 'neutral' | 'success' | 'warning' | 'danger'", "'primary'", 'La palette utilisée.'],
        ['size', "'sm' | 'md' | 'lg'", "'md'", 'Hauteur, marges internes et taille du libellé.'],
        ['href', 'string', '', 'Rend une <a> au lieu d’un <button>.'],
        ['startIcon', 'string', '', 'Balisage placé avant le libellé.'],
        ['endIcon', 'string', '', 'Balisage placé après le libellé.'],
        ['loading', 'boolean', 'false', 'Affiche un spinner et pose aria-busy.'],
        ['disabled', 'boolean', 'false', 'Désactive le bouton, ou marque un lien aria-disabled.'],
        ['block', 'boolean', 'false', 'S’étire sur toute la largeur du conteneur.'],
        ['type', "'button' | 'submit' | 'reset'", "'button'", 'Uniquement pour la forme <button>.'],
      ]),
      p(
        code('iconButton()'),
        ' prend les mêmes props plus un ',
        code('label'),
        ' obligatoire et une ',
        code('icon'),
        '.',
      ),
    ],
  })
