import { h2, p } from 'javascript-to-html'
import { code, demo, propsTable, uiLayout } from '../../lib/es.js'

export default () =>
  uiLayout({
    title: 'Botón',
    description:
      'Los botones dejan que la gente actúe. Cinco variantes, cinco colores, tres tamaños — y un ancla siempre que navega.',
    activeHref: '/es/ui/button',
    children: [
      p(
        'Un botón es aquello que una persona pulsa para que ocurra algo. ',
        code('button()'),
        ' dibuja un ',
        code('<button>'),
        ' de verdad con ',
        code('type="button"'),
        ', así que dejar uno dentro de un formulario no lo envía por accidente.',
      ),

      h2('Botón básico'),
      p(
        'Por defecto es un botón sólido, primary y mediano. Los hijos son la etiqueta; todo lo demás es una prop.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  button('Uno'),
  button('Dos'),
  button('Tres'),
)`),

      h2('Variantes'),
      p(
        'Cinco niveles de énfasis, desde la única llamada a la acción de la página hasta algo que se lee como un enlace.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'solid' }, 'Solid'),
  button({ variant: 'soft' }, 'Soft'),
  button({ variant: 'outline' }, 'Outline'),
  button({ variant: 'ghost' }, 'Ghost'),
  button({ variant: 'link' }, 'Link'),
)`),

      h2('Colores'),
      p(
        'Todos los componentes con tema beben de las mismas cinco paletas, así que un botón ',
        code("color: 'danger'"),
        ' y una alerta ',
        code("color: 'danger'"),
        ' concuerdan sin que ninguno sepa del otro.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ color: 'primary' }, 'Primary'),
  button({ color: 'neutral' }, 'Neutral'),
  button({ color: 'success' }, 'Success'),
  button({ color: 'warning' }, 'Warning'),
  button({ color: 'danger' }, 'Danger'),
)`),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'soft', color: 'primary' }, 'Primary'),
  button({ variant: 'soft', color: 'neutral' }, 'Neutral'),
  button({ variant: 'soft', color: 'success' }, 'Success'),
  button({ variant: 'soft', color: 'warning' }, 'Warning'),
  button({ variant: 'soft', color: 'danger' }, 'Danger'),
)`),

      h2('Tamaños'),
      demo(`stack({ direction: 'row', gap: 'md', align: 'center', wrap: true },
  button({ size: 'sm' }, 'Pequeño'),
  button({ size: 'md' }, 'Mediano'),
  button({ size: 'lg' }, 'Grande'),
)`),

      h2('Iconos'),
      p(
        'Pasa cualquier marcado SVG en ',
        code('startIcon'),
        ' o ',
        code('endIcon'),
        '. Los iconos se dimensionan en ',
        code('em'),
        ', así que escalan con el botón en vez de necesitar un tamaño propio.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({
    startIcon: icon('plus'),
  }, 'Página nueva'),
  button({
    variant: 'outline',
    endIcon: icon('arrow-right'),
  }, 'Continuar'),
)`),

      h2('Botón de icono'),
      p(
        code('iconButton()'),
        ' es un botón cuadrado con un solo icono. Su ',
        code('label'),
        ' es obligatorio: pasa a ser el nombre accesible que el icono por sí solo no puede dar, y el tooltip al pasar por encima.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  iconButton({ label: 'Añadir', icon: icon('plus') }),
  iconButton({ label: 'Editar', variant: 'soft', icon: icon('edit') }),
  iconButton({ label: 'Eliminar', variant: 'ghost', color: 'danger', icon: icon('trash') }),
)`),

      h2('Cargando y deshabilitado'),
      p(
        code('loading'),
        ' pone un spinner y activa ',
        code('aria-busy'),
        ', dejando la etiqueta en su sitio para que el botón no cambie de ancho a mitad de la acción.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ loading: true }, 'Guardando'),
  button({ variant: 'outline', loading: true }, 'Comprobando'),
  button({ disabled: true }, 'Deshabilitado'),
  button({ variant: 'soft', disabled: true }, 'Deshabilitado'),
)`),

      h2('Enlaces'),
      p(
        'Dale a un botón un ',
        code('href'),
        ' y dibujará un ',
        code('<a>'),
        ' en su lugar: el elemento correcto para algo que navega. Las anclas no tienen estado deshabilitado, así que ',
        code('disabled'),
        ' se convierte en ',
        code('aria-disabled'),
        ' y la saca del orden de tabulación.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ href: '/es/docs' }, 'Leer la documentación'),
  button({ href: '/es/docs/ui', variant: 'outline' }, 'Componentes'),
  button({ href: '/es/docs', variant: 'link' }, 'Enlace simple'),
)`),

      h2('Ancho completo'),
      demo(`button({ block: true, size: 'lg' }, 'Desplegar el sitio')`, { align: 'stretch' }),

      h2('Props'),
      p(
        'Todo lo que no esté listado aquí cae al elemento renderizado como atributo: ',
        code('id'),
        ', ',
        code('data-*'),
        ', ',
        code('onclick'),
        ', ',
        code('popovertarget'),
        ' y demás.',
      ),
      propsTable([
        ['variant', "'solid' | 'soft' | 'outline' | 'ghost' | 'link'", "'solid'", 'Cuánto énfasis lleva el botón.'],
        ['color', "'primary' | 'neutral' | 'success' | 'warning' | 'danger'", "'primary'", 'De qué paleta bebe.'],
        ['size', "'sm' | 'md' | 'lg'", "'md'", 'Altura, relleno y tamaño de la etiqueta.'],
        ['href', 'string', '', 'Dibuja un <a> en vez de un <button>.'],
        ['startIcon', 'string', '', 'Marcado colocado antes de la etiqueta.'],
        ['endIcon', 'string', '', 'Marcado colocado después de la etiqueta.'],
        ['loading', 'boolean', 'false', 'Muestra un spinner y activa aria-busy.'],
        ['disabled', 'boolean', 'false', 'Deshabilita el botón, o marca un enlace como aria-disabled.'],
        ['block', 'boolean', 'false', 'Se estira al ancho completo de su contenedor.'],
        ['type', "'button' | 'submit' | 'reset'", "'button'", 'Solo para la forma <button>.'],
      ]),
      p(
        code('iconButton()'),
        ' admite las mismas props más un ',
        code('label'),
        ' obligatorio y un ',
        code('icon'),
        '.',
      ),
    ],
  })
