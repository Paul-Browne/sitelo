import { h2, p } from 'javascript-to-html'
import { code, demo, propsTable, uiLayout } from '../../lib/pt.js'
import { uiHead } from '../../lib/ui-demo.js'

export default () =>
  uiLayout({
    title: 'Botão',
    description:
      'Os botões deixam as pessoas agir. Cinco variantes, cinco cores, três tamanhos — e uma âncora sempre que navega.',
    activeHref: '/pt/ui/button',
    extraHead: uiHead(),
    children: [
      p(
        'Um botão é aquilo em que se carrega para algo acontecer. ',
        code('button()'),
        ' desenha um ',
        code('<button>'),
        ' a sério, com ',
        code('type="button"'),
        ', por isso pôr um dentro de um formulário não o submete por acidente.',
      ),

      h2('Botão básico'),
      p(
        'A predefinição é um botão sólido, primary, de tamanho médio. Os filhos são a etiqueta; tudo o resto é uma prop.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  button('Um'),
  button('Dois'),
  button('Três'),
)`),

      h2('Variantes'),
      p(
        'Cinco níveis de ênfase, do único apelo à ação da página até algo que se lê como uma ligação.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'solid' }, 'Solid'),
  button({ variant: 'soft' }, 'Soft'),
  button({ variant: 'outline' }, 'Outline'),
  button({ variant: 'ghost' }, 'Ghost'),
  button({ variant: 'link' }, 'Link'),
)`),

      h2('Cores'),
      p(
        'Todos os componentes com tema bebem das mesmas cinco paletas, por isso um botão ',
        code("color: 'danger'"),
        ' e um alerta ',
        code("color: 'danger'"),
        ' combinam sem que nenhum saiba do outro.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ color: 'primary' }, 'Primary'),
  button({ color: 'neutral' }, 'Neutral'),
  button({ color: 'success' }, 'Success'),
  button({ color: 'warning' }, 'Warning'),
  button({ color: 'danger' }, 'Danger'),
)`),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'soft', color: 'primary' }, 'Primary'),
  button({ variant: 'soft', color: 'neutral' }, 'Neutral'),
  button({ variant: 'soft', color: 'success' }, 'Success'),
  button({ variant: 'soft', color: 'warning' }, 'Warning'),
  button({ variant: 'soft', color: 'danger' }, 'Danger'),
)`),

      h2('Tamanhos'),
      demo(`stack({ direction: 'row', gap: 'md', align: 'center', wrap: true },
  button({ size: 'sm' }, 'Pequeno'),
  button({ size: 'md' }, 'Médio'),
  button({ size: 'lg' }, 'Grande'),
)`),

      h2('Ícones'),
      p(
        'Passa qualquer marcação SVG em ',
        code('startIcon'),
        ' ou ',
        code('endIcon'),
        '. Os ícones são dimensionados em ',
        code('em'),
        ', por isso acompanham o botão em vez de precisarem de um tamanho próprio.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({
    startIcon: icon('plus'),
  }, 'Página nova'),
  button({
    variant: 'outline',
    endIcon: icon('arrow-right'),
  }, 'Continuar'),
)`),

      h2('Botão de ícone'),
      p(
        code('iconButton()'),
        ' é um botão quadrado com um único ícone. O seu ',
        code('label'),
        ' é obrigatório — passa a ser o nome acessível que o ícone sozinho não consegue dar, e a dica ao passar o rato.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  iconButton({ label: 'Adicionar', icon: icon('plus') }),
  iconButton({ label: 'Editar', variant: 'soft', icon: icon('edit') }),
  iconButton({ label: 'Eliminar', variant: 'ghost', color: 'danger', icon: icon('trash') }),
)`),

      h2('A carregar e desativado'),
      p(
        code('loading'),
        ' troca por um indicador giratório e define ',
        code('aria-busy'),
        ', deixando a etiqueta no lugar para que o botão não mude de largura a meio da ação.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ loading: true }, 'A guardar'),
  button({ variant: 'outline', loading: true }, 'A verificar'),
  button({ disabled: true }, 'Desativado'),
  button({ variant: 'soft', disabled: true }, 'Desativado'),
)`),

      h2('Ligações'),
      p(
        'Dá a um botão um ',
        code('href'),
        ' e ele desenha um ',
        code('<a>'),
        ' — o elemento certo para algo que navega. As âncoras não têm estado desativado, por isso ',
        code('disabled'),
        ' torna-se ',
        code('aria-disabled'),
        ' e retira-a da ordem de tabulação.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ href: '/pt/docs' }, 'Ler a documentação'),
  button({ href: '/pt/docs/ui', variant: 'outline' }, 'Componentes'),
  button({ href: '/pt/docs', variant: 'link' }, 'Ligação simples'),
)`),

      h2('Largura total'),
      demo(`button({ block: true, size: 'lg' }, 'Publicar o site')`, { align: 'stretch' }),

      h2('Props'),
      p(
        'Tudo o que não estiver listado aqui cai no elemento renderizado como atributo — ',
        code('id'),
        ', ',
        code('data-*'),
        ', ',
        code('onclick'),
        ', ',
        code('popovertarget'),
        ' e os restantes.',
      ),
      propsTable([
        ['variant', "'solid' | 'soft' | 'outline' | 'ghost' | 'link'", "'solid'", 'Quanta ênfase o botão carrega.'],
        ['color', "'primary' | 'neutral' | 'success' | 'warning' | 'danger'", "'primary'", 'De que paleta bebe.'],
        ['size', "'sm' | 'md' | 'lg'", "'md'", 'Altura, espaçamento e tamanho da etiqueta.'],
        ['href', 'string', '', 'Desenha um <a> em vez de um <button>.'],
        ['startIcon', 'string', '', 'Marcação colocada antes da etiqueta.'],
        ['endIcon', 'string', '', 'Marcação colocada depois da etiqueta.'],
        ['loading', 'boolean', 'false', 'Mostra um indicador giratório e define aria-busy.'],
        ['disabled', 'boolean', 'false', 'Desativa o botão, ou marca uma ligação como aria-disabled.'],
        ['block', 'boolean', 'false', 'Estica até à largura total do contentor.'],
        ['type', "'button' | 'submit' | 'reset'", "'button'", 'Só para a forma <button>.'],
      ]),
      p(
        code('iconButton()'),
        ' aceita as mesmas props mais um ',
        code('label'),
        ' obrigatório e um ',
        code('icon'),
        '.',
      ),
    ],
  })
