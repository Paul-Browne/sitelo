import { h2, p } from 'javascript-to-html'
import { code } from '../lib/code.js'
import { uiLayout } from '../lib/layout.js'
import { demo, propsTable, uiStyles } from '../lib/ui-demo.js'

export default () =>
  uiLayout({
    title: 'Button',
    description:
      'Buttons let people take an action. Five variants, five colors, three sizes — and an anchor whenever it navigates.',
    activeHref: '/ui/button',
    extraHead: uiStyles(),
    children: [
      p(
        'A button is the thing a person clicks to make something happen. ',
        code('button()'),
        ' renders a real ',
        code('<button>'),
        ' with ',
        code('type="button"'),
        ', so dropping one inside a form does not submit it by accident.',
      ),

      h2('Basic button'),
      p(
        'The default is a solid, primary, medium button. Children are the label; anything else is a prop.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  button('One'),
  button('Two'),
  button('Three'),
)`),

      h2('Variants'),
      p(
        'Five levels of emphasis, from the one call to action on the page down to something that reads as a link.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'solid' }, 'Solid'),
  button({ variant: 'soft' }, 'Soft'),
  button({ variant: 'outline' }, 'Outline'),
  button({ variant: 'ghost' }, 'Ghost'),
  button({ variant: 'link' }, 'Link'),
)`),

      h2('Colors'),
      p(
        'Every themed component draws from the same five palettes, so a ',
        code("color: 'danger'"),
        ' button and a ',
        code("color: 'danger'"),
        ' alert agree without either of them knowing about the other.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ color: 'primary' }, 'Primary'),
  button({ color: 'neutral' }, 'Neutral'),
  button({ color: 'success' }, 'Success'),
  button({ color: 'warning' }, 'Warning'),
  button({ color: 'danger' }, 'Danger'),
)`),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ variant: 'soft', color: 'primary' }, 'Primary'),
  button({ variant: 'soft', color: 'neutral' }, 'Neutral'),
  button({ variant: 'soft', color: 'success' }, 'Success'),
  button({ variant: 'soft', color: 'warning' }, 'Warning'),
  button({ variant: 'soft', color: 'danger' }, 'Danger'),
)`),

      h2('Sizes'),
      demo(`stack({ direction: 'row', gap: 'md', align: 'center', wrap: true },
  button({ size: 'sm' }, 'Small'),
  button({ size: 'md' }, 'Medium'),
  button({ size: 'lg' }, 'Large'),
)`),

      h2('Icons'),
      p(
        'Pass any SVG markup as ',
        code('startIcon'),
        ' or ',
        code('endIcon'),
        '. Icons are sized in ',
        code('em'),
        ', so they scale with the button rather than needing a size of their own.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({
    startIcon: '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M10 4v12M4 10h12"/></svg>',
  }, 'New page'),
  button({
    variant: 'outline',
    endIcon: '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M4 10h12M11 5l5 5-5 5"/></svg>',
  }, 'Continue'),
)`),

      h2('Icon button'),
      p(
        code('iconButton()'),
        ' is a square button holding a single icon. Its ',
        code('label'),
        ' is required — it becomes the accessible name that the icon itself cannot provide, and the tooltip on hover.',
      ),
      demo(`stack({ direction: 'row', gap: 'md' },
  iconButton({ label: 'Add', icon: '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M10 4v12M4 10h12"/></svg>' }),
  iconButton({ label: 'Edit', variant: 'soft', icon: '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linejoin="round"><path d="m4 16 1-3 8-8 2 2-8 8z"/></svg>' }),
  iconButton({ label: 'Delete', variant: 'ghost', color: 'danger', icon: '<svg viewBox="0 0 20 20" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"><path d="M4 6h12M8 6V4h4v2M7 6l.7 10h4.6L13 6"/></svg>' }),
)`),

      h2('Loading and disabled'),
      p(
        code('loading'),
        ' swaps in a spinner and sets ',
        code('aria-busy'),
        ', leaving the label in place so the button does not change width mid-action.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ loading: true }, 'Saving'),
  button({ variant: 'outline', loading: true }, 'Checking'),
  button({ disabled: true }, 'Disabled'),
  button({ variant: 'soft', disabled: true }, 'Disabled'),
)`),

      h2('Links'),
      p(
        'Give a button an ',
        code('href'),
        ' and it renders an ',
        code('<a>'),
        ' instead — the right element for something that navigates. Anchors have no disabled state, so ',
        code('disabled'),
        ' becomes ',
        code('aria-disabled'),
        ' and removes it from the tab order.',
      ),
      demo(`stack({ direction: 'row', gap: 'md', wrap: true },
  button({ href: '/docs' }, 'Read the docs'),
  button({ href: '/docs/ui', variant: 'outline' }, 'Components'),
  button({ href: '/docs', variant: 'link' }, 'Plain link'),
)`),

      h2('Full width'),
      demo(`button({ block: true, size: 'lg' }, 'Deploy site')`, { align: 'stretch' }),

      h2('Props'),
      p(
        'Anything not listed here falls through to the rendered element as an attribute — ',
        code('id'),
        ', ',
        code('data-*'),
        ', ',
        code('onclick'),
        ', ',
        code('popovertarget'),
        ' and the rest.',
      ),
      propsTable([
        ['variant', "'solid' | 'soft' | 'outline' | 'ghost' | 'link'", "'solid'", 'How much emphasis the button carries.'],
        ['color', "'primary' | 'neutral' | 'success' | 'warning' | 'danger'", "'primary'", 'Which palette to draw from.'],
        ['size', "'sm' | 'md' | 'lg'", "'md'", 'Height, padding and label size.'],
        ['href', 'string', '', 'Renders an <a> instead of a <button>.'],
        ['startIcon', 'string', '', 'Markup placed before the label.'],
        ['endIcon', 'string', '', 'Markup placed after the label.'],
        ['loading', 'boolean', 'false', 'Shows a spinner and sets aria-busy.'],
        ['disabled', 'boolean', 'false', 'Disables the button, or marks a link aria-disabled.'],
        ['block', 'boolean', 'false', 'Stretches to the full width of its container.'],
        ['type', "'button' | 'submit' | 'reset'", "'button'", 'Only for the <button> form.'],
      ]),
      p(
        code('iconButton()'),
        ' takes the same props plus a required ',
        code('label'),
        ' and an ',
        code('icon'),
        '.',
      ),
    ],
  })
