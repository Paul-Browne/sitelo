import {
  a,
  div,
  h2,
  h3,
  li,
  p,
  strong,
  table,
  tbody,
  td,
  th,
  thead,
  tr,
  ul,
} from 'javascript-to-html'
import { code, codeBlock } from '../lib/code.js'
import { docsLayout } from '../lib/layout.js'
import { uiSnippets } from '../lib/snippets/ui.js'

const s = uiSnippets('en')

/** The component reference table, one row per group. */
const GROUPS = [
  ['Layout', ['container', 'stack', 'grid', 'divider', 'card', 'cardHeader', 'cardTitle', 'cardSubtitle', 'cardMedia', 'cardBody', 'cardFooter']],
  ['Typography', ['text', 'heading', 'link', 'code', 'kbd', 'visuallyHidden']],
  ['Inputs', ['button', 'iconButton', 'buttonGroup', 'field', 'input', 'textarea', 'select', 'textField', 'textareaField', 'selectField', 'checkbox', 'radio', 'toggle', 'choiceGroup']],
  ['Data display', ['avatar', 'avatarGroup', 'badge', 'chip', 'tooltip', 'table', 'list', 'listItem']],
  ['Feedback', ['alert', 'progress', 'spinner', 'skeleton', 'toasts']],
  ['Navigation', ['breadcrumbs', 'pagination', 'tabs', 'appBar', 'appBarNav', 'appBarSpacer', 'appBarActions', 'navLink', 'themeToggle']],
  ['Overlays', ['modal', 'drawer', 'closeButton', 'menu', 'menuItem', 'menuSeparator', 'accordion', 'accordionItem']],
  ['Styling', ['styles', 'stylesheet', 'theme', 'themeScript']],
]

export default () =>
  docsLayout({
    title: 'Components',
    description:
      'sitelo-ui: buttons, cards, forms, tables, modals and the rest, as functions that return HTML.',
    activeHref: '/docs/ui',
    children: [
      p(
        'sitelo-ui is a component library for sitelo. Every component is a function that returns a string of HTML, so it nests straight into a ',
        a({ href: 'https://www.npmjs.com/package/javascript-to-html' }, 'javascript-to-html'),
        ' tree with nothing in between — no compiler, no runtime, no hydration. What you build is what lands in ',
        code('dist/'),
        '.',
      ),
      p(
        'It ships with sitelo, under the ',
        code('sitelo/ui'),
        ' entry point.',
      ),

      h2('Quick start'),
      codeBlock('Terminal', s.install, 'bash'),
      p(
        'Put ',
        code('styles()'),
        ' in the head and call components in the body. That is the whole setup:',
      ),
      codeBlock('src/index.ht.js', s.page, 'javascript'),
      p(
        'Component names deliberately match what they render, which means a few of them — ',
        code('button'),
        ', ',
        code('input'),
        ', ',
        code('table'),
        ', ',
        code('link'),
        ', ',
        code('code'),
        ', ',
        code('select'),
        ', ',
        code('progress'),
        ' — collide with javascript-to-html’s element functions. Import the library as a namespace when you need both:',
      ),
      codeBlock('src/index.ht.js', s.namespace, 'javascript'),

      h2('The calling convention'),
      p(
        'Every component takes an optional props object followed by children, exactly like a javascript-to-html element. Props the component understands are consumed by name; ',
        strong('everything else falls through to the rendered element as an attribute'),
        ', so ',
        code('id'),
        ', ',
        code('data-*'),
        ', ',
        code('aria-*'),
        ' and event attributes work without the library having to list them:',
      ),
      codeBlock('Pass-through props', s.passthrough, 'javascript'),
      p(
        'A prop the component does not recognise the value of — ',
        code('variant: \'nonsense\''),
        ' — falls back to the default rather than throwing. A cosmetic typo should not fail a build.',
      ),

      h2('Styling'),
      p(
        code('styles()'),
        ' returns a ',
        code('<style>'),
        ' element holding the whole sheet, minified. It is around 7 kB over the wire and cannot go missing from ',
        code('dist/'),
        ', which is why it is the default. If you would rather link it once and let the browser cache it across pages, import the CSS from a bundled entry file instead and Vite will emit it:',
      ),
      codeBlock('src/main.js', s.linked, 'javascript'),
      p('Use one or the other, not both.'),

      h3('Theming'),
      p(
        'Everything is driven by CSS custom properties on ',
        code(':root'),
        ' — five palettes, a spacing scale, radii, type and shadows. ',
        code('theme()'),
        ' writes overrides for them, and takes camelCase names (',
        code('radiusMd'),
        ' → ',
        code('--su-radius-md'),
        '), palette objects, or literal custom properties:',
      ),
      codeBlock('src/index.ht.js', s.theming, 'javascript'),
      p(
        'Dark mode resolves from ',
        code('prefers-color-scheme'),
        ' on its own. Setting ',
        code('data-theme'),
        ' or ',
        code('data-su-theme'),
        ' to ',
        code('light'),
        ' or ',
        code('dark'),
        ' on any ancestor overrides it — which is what ',
        code('themeToggle()'),
        ' does:',
      ),
      codeBlock('src/index.ht.js', s.themeToggle, 'javascript'),

      h2('JavaScript, and how little of it there is'),
      p(
        'Most components need none. The modal and the drawer are ',
        code('popover'),
        ' elements, so the browser handles opening, the backdrop, click-outside and Escape. The accordion is ',
        code('<details name>'),
        '. Menus are ',
        code('<details>'),
        '. Tooltips are CSS.',
      ),
      p('Four things do want a script:'),
      ul(
        li('tabs whose panels swap in place'),
        li('the close button on a dismissible alert'),
        li(
          code('toast()'),
          ' and the ',
          code('toasts()'),
          ' region',
        ),
        li('the theme toggle'),
      ),
      p('Import it from any bundled entry file:'),
      codeBlock('src/main.js', s.client, 'javascript'),
      p('It is about 3 kB, listens on the document rather than per element, and every component it touches renders correctly with it absent — panel tabs show the panel the server marked active, menus still open, the dismiss button simply does nothing.'),

      h2('Examples'),
      p('Forms wire their own labels, ids, help text and error messages:'),
      codeBlock('A form', s.form, 'javascript'),
      p('A modal is a popover and its trigger is any button pointing at its id:'),
      codeBlock('A modal', s.modal, 'javascript'),
      p('Tabs come in two shapes — links, or panels:'),
      codeBlock('Tabs', s.tabs, 'javascript'),
      p(
        'Tables take ',
        code('columns'),
        ' and ',
        code('rows'),
        ', with a ',
        code('render'),
        ' function wherever a cell needs more than a value:',
      ),
      codeBlock('A table', s.table, 'javascript'),
      p(
        'The ',
        code('examples/ui'),
        ' directory in the repository renders every component on one page — it is the fastest way to see the whole set.',
      ),

      h2('Component reference'),
      p(
        'Every export, by group. Props are typed: ',
        code('sitelo/ui'),
        ' ships ',
        code('.d.ts'),
        ' files, so an editor completes ',
        code('variant'),
        ', ',
        code('color'),
        ' and ',
        code('size'),
        ' for you in JavaScript as well as TypeScript.',
      ),
      div(
        { class: 'docs-table-scroll' },
        table(
          { class: 'docs-table docs-table--wrap-last' },
          thead(tr(th('Group'), th('Components'))),
          tbody(
            ...GROUPS.map(([group, names]) =>
              tr(td(group), td(names.map((name) => code(name)).join(', '))),
            ),
          ),
        ),
      ),
      p(
        'Two names differ from what you might expect: the switch is ',
        code('toggle'),
        ', because ',
        code('switch'),
        ' is a reserved word and cannot be an import binding; and the styled anchor is exported as both ',
        code('link'),
        ' and ',
        code('textLink'),
        ', so it can sit alongside javascript-to-html’s ',
        code('link'),
        '. ',
        code('table'),
        ', ',
        code('input'),
        ', ',
        code('select'),
        ' and ',
        code('progress'),
        ' have the same escape hatch: ',
        code('dataTable'),
        ', ',
        code('textInput'),
        ', ',
        code('selectField'),
        ', ',
        code('progressBar'),
        '.',
      ),
    ],
  })
