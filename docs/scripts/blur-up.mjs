/**
 * Regenerates src/lib/blur-up-photos.js, the data behind the demo under
 * "Blur-up placeholders" on the images page: for each photo in
 * public/images/blur-up/, the placeholder sitelo paints behind it.
 *
 * The docs site doesn't optimize its own images, so the demo can't take
 * them from the build. This runs the pipeline `sitelo dev` runs, with
 * `placeholder: true`, over each photo and keeps the `style` and `onload`
 * it wrote on the tag — so the demo shows what a site actually gets, and
 * what it costs in the page.
 *
 * Run `npm run docs:blur-up` after changing the photos or how placeholders
 * are made, then commit the file it writes. Needs sharp, already an
 * optional peer for image optimization.
 *
 * The photos are from Unsplash, free to use under the Unsplash License,
 * cropped to 720×480 — twice a tile's width on a desktop screen.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import {
  createDevImagePipeline,
  normalizeImageOptions,
  parseAttributes,
} from '../../src/images.js'

const docsDir = fileURLToPath(new URL('..', import.meta.url))
const out = fileURLToPath(new URL('../src/lib/blur-up-photos.js', import.meta.url))

/** In the order the demo shows them. */
const PHOTOS = [
  { name: 'fjord', by: 'Alexey Topolyanskiy', from: 'https://unsplash.com/photos/-oWyJoSqBRM' },
  { name: 'pug', by: 'Matthew Wiebe', from: 'https://unsplash.com/photos/U5rMrSI7Pn4' },
  { name: 'jellyfish', by: 'Marat Gilyadzinov', from: 'https://unsplash.com/photos/wpTWYBll4_w' },
  { name: 'walrus', by: 'Jay Ruzesky', from: 'https://unsplash.com/photos/h13Y8vyIXNU' },
]

// A cache of its own, so the placeholders are made now rather than read
// back from whatever an earlier version of the code wrote.
const cacheDir = fs.mkdtempSync(path.join(os.tmpdir(), 'sitelo-blur-up-'))
const warnings = []

try {
  const pipeline = createDevImagePipeline({
    root: docsDir,
    options: normalizeImageOptions({ placeholder: true, cacheDir }),
    warn: (message) => warnings.push(message),
  })

  const photos = []

  for (const { name, by, from } of PHOTOS) {
    const src = `/images/blur-up/${name}.jpg`
    const html = await pipeline.transform(`<img src="${src}" alt="">`)
    const attributes = parseAttributes(html.match(/<img\b[^>]*>/)[0])
    const style = attributes.get('style')
    const onload = attributes.get('onload')

    if (!style || !onload) {
      throw new Error(`${src} got no placeholder${warnings.length ? `:\n${warnings.join('\n')}` : ''}`)
    }

    photos.push({
      name,
      src,
      width: Number(attributes.get('width')),
      height: Number(attributes.get('height')),
      style,
      // What the two attributes add to the page, as they are written there.
      pageBytes: Buffer.byteLength(
        (html.match(/ style="[^"]*"/)?.[0] ?? '') + (html.match(/ onload="[^"]*"/)?.[0] ?? ''),
      ),
      photoBytes: fs.statSync(path.join(docsDir, 'public', src)).size,
      by,
      from,
    })
  }

  fs.writeFileSync(
    out,
    '/*\n' +
      ' * Generated by docs/scripts/blur-up.mjs from the photos in\n' +
      ' * public/images/blur-up/. Run `npm run docs:blur-up` to remake it.\n' +
      ' */\n' +
      `export const BLUR_UP_PHOTOS = ${JSON.stringify(photos, null, 2)}\n`,
  )

  for (const photo of photos) {
    console.log(`${photo.name}: ${photo.pageBytes} B in the page for a ${photo.photoBytes} B photo`)
  }
} finally {
  fs.rmSync(cacheDir, { recursive: true, force: true })
}
